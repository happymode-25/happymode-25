def render(text):
    rows = ["" for _ in range(7)]
    for ch in text.upper():
        glyph = FONT.get(ch, FONT[" "])
        for i in range(7):
            rows[i] += glyph[i] + " "
    return "\n".join(r.rstrip() for r in rows)


